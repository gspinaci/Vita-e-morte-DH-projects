"""Column names of the project dataset (public schema of the Zenodo release).

The 16 *curated* columns are edited by hand in ``data/curated/projects.csv``.
The 8 *archive* columns are generated by ``dhlife.archive_check``.
"""

import pandas as pd

CURATED_COLUMNS = [
    "institution",
    "title",
    "project_url",
    "functioning_website",
    "website_not_found",
    "non_functioning_website",
    "not_redirected_website",
    "partially_unaccessible_website",
    "new_website_url",
    "url_showcase",
    "url_showcase_working",
    "url_landing_page",
    "url_landing_working",
    "provenance",
    "knot_uri",
    "notes",
]

BOOLEAN_COLUMNS = [
    "functioning_website",
    "website_not_found",
    "non_functioning_website",
    "not_redirected_website",
    "partially_unaccessible_website",
    "url_showcase_working",
    "url_landing_working",
]

# URL column -> prefix of the four archive columns derived from it.
ARCHIVED_URL_COLUMNS = {
    "project_url": "",
    "url_showcase": "showcase_",
}


def archive_columns(prefix: str) -> list[str]:
    return [
        f"{prefix}url_first_seen",
        f"{prefix}url_last_seen",
        f"{prefix}url_status_code",
        f"{prefix}last_url_snapshot",
    ]


ARCHIVE_COLUMNS = [c for p in ARCHIVED_URL_COLUMNS.values() for c in archive_columns(p)]
RELEASE_COLUMNS = CURATED_COLUMNS + ARCHIVE_COLUMNS

PROVENANCES = [
    "Italian DH Institutions",
    "KNOT",
    "AIUCD",
    "IRCDL",
    "DH Awards",
    "Catalogue Digital Editions",
]

# Sentinels written in the archive columns.
NOT_PROVIDED = "NOTPROVIDED"  # project has no (valid) URL
NO_STATUS_CODE = "NOSTATUSCODE"  # live HTTP check failed (DNS, timeout, TLS...)

DATE_FORMAT = "%Y-%m-%d %H:%M:%S"


def read_projects(path) -> pd.DataFrame:
    """Read a project CSV with real booleans and everything else as strings."""
    df = pd.read_csv(path, dtype=str, keep_default_na=False, na_values=[""])
    for col in BOOLEAN_COLUMNS:
        if col in df:
            df[col] = df[col].str.upper().map({"TRUE": True, "FALSE": False})
    return df


def write_projects(df: pd.DataFrame, path) -> None:
    out = df.copy()
    for col in BOOLEAN_COLUMNS:
        if col in out:
            out[col] = out[col].map({True: "TRUE", False: "FALSE"})
    out.to_csv(path, index=False)
